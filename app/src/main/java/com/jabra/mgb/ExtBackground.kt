package com.jabra.mgb

import android.annotation.SuppressLint
import android.content.Context
import android.os.Handler
import android.os.Looper
import android.os.SystemClock
import android.util.Log
import android.webkit.ConsoleMessage
import android.webkit.RenderProcessGoneDetail
import android.webkit.WebChromeClient
import android.webkit.WebResourceError
import android.webkit.WebResourceRequest
import android.webkit.WebResourceResponse
import android.webkit.WebView
import android.webkit.WebViewClient
import org.json.JSONObject
import java.io.ByteArrayInputStream
import java.io.File

/**
 * S5: background service worker of an installed MV3 extension = one hidden WebView per extension.
 *  - Page: https://appassets.androidplatform.net/ext/<id>/_mgb_bg.html (generated by EngineHost.page -> page()):
 *    importScripts shim (sync XHR + eval), a few service worker globals, then the manifest service_worker file
 *    as a classic script (or type=module). install / activate events are dispatched after load.
 *  - Lazy: nothing runs until ensure(id) is called (message to the extension, alarm, remembered event, onInstalled).
 *  - Idle: no bridge call / network request / pending reply for IDLE_MS -> the WebView is destroyed (like Chrome's 30 s rule).
 *  - Limits: at most MAX_RUNNING workers (least recently used one is stopped); 3 render crashes in 5 minutes park the
 *    extension's worker until it is toggled or the app restarts. One broken extension never touches the others.
 *  - Isolation: the worker may only read its own files below ext/<id>/; network only through its host permissions.
 */
object ExtBackground {
    private const val TAG = "MGB.extbg"
    const val PAGE = "_mgb_bg.html"
    private const val LOAD_TIMEOUT_MS = 20_000L
    private const val SETTLE_MS = 300L
    private const val IDLE_MS = 45_000L
    private const val TICK_MS = 10_000L
    private const val MAX_RUNNING = 3
    private const val CRASH_LIMIT = 3
    private const val CRASH_WINDOW_MS = 5 * 60_000L

    // importScripts = synchronous XHR + global eval; the rest are inert service worker globals
    private const val PRE = """(function(){var S=self;S.importScripts=function(){for(var i=0;i<arguments.length;i++){var u=new URL(arguments[i],location.href).href;var x=new XMLHttpRequest();x.open('GET',u,false);x.send();if(x.status!==200)throw new Error('importScripts failed: '+u+' ('+x.status+')');(0,eval)(x.responseText+'\n//# sourceURL='+u);}};S.skipWaiting=function(){return Promise.resolve();};S.clients={claim:function(){return Promise.resolve();},matchAll:function(){return Promise.resolve([]);},get:function(){return Promise.resolve(undefined);},openWindow:function(){return Promise.resolve(null);}};S.registration={scope:location.origin+'/ext/',showNotification:function(){return Promise.resolve();}};})();"""
    private const val POST = """addEventListener('load',function(){['install','activate'].forEach(function(n){try{var e=new Event(n);e.waitUntil=function(){};dispatchEvent(e);}catch(x){}});});"""

    private class Bg(val id: String, val web: WebView) {
        var loaded = false
        var ready = false
        var busy = 0
        var lastActive = SystemClock.uptimeMillis()
        val waiters = ArrayList<(Boolean) -> Unit>()
        var timeout: Runnable? = null
    }

    private class Sw(val path: String, val module: Boolean)
    private class SwCache(val sig: String, val sw: Sw?)

    private val main = Handler(Looper.getMainLooper())
    private var app: Context? = null
    private var ticking = false
    private val bgs = LinkedHashMap<String, Bg>()
    private val crashes = HashMap<String, ArrayList<Long>>()
    private val parked = HashSet<String>()
    private val swCache = HashMap<String, SwCache>()
    private val logs = HashMap<String, ArrayList<String>>()

    private fun ui(b: () -> Unit) {
        if (Looper.myLooper() == Looper.getMainLooper()) b() else main.post { b() }
    }

    fun init(ctx: Context) {
        app = ctx.applicationContext
    }

    // ---------- manifest ----------

    private fun swOf(id: String): Sw? {
        if (!ExtRegistry.isValidId(id)) return null
        val info = ExtRegistry.get(id) ?: return null
        if (!info.enabled) return null
        return try {
            val mf = File(info.dir, "manifest.json")
            if (!mf.isFile || mf.length() > 2_000_000L) return null
            val sig = info.version + ":" + mf.lastModified()
            val hit = swCache[id]
            if (hit != null && hit.sig == sig) return hit.sw
            val bgo = JSONObject(mf.readText()).optJSONObject("background")
            var sw: Sw? = null
            if (bgo != null) {
                val p = bgo.optString("service_worker", "").trimStart('/')
                val bad = p.isEmpty() || p.contains("..") || p.contains("://") || p.contains('?') || p.contains('#')
                if (!bad && ExtRegistry.file(id, p) != null) sw = Sw(p, bgo.optString("type") == "module")
            }
            swCache[id] = SwCache(sig, sw)
            sw
        } catch (e: Exception) {
            null
        }
    }

    /** True if this enabled extension has a service worker we can run. */
    fun has(id: String): Boolean = swOf(id) != null

    fun running(id: String): Boolean = bgs[id] != null

    fun idOf(w: WebView): String? = bgs.values.firstOrNull { it.web === w }?.id

    fun urlOf(id: String): String = ContentInjector.EXT_BASE + id + "/" + (swOf(id)?.path ?: PAGE)

    fun reset(id: String) {
        crashes.remove(id)
        parked.remove(id)
    }

    private fun nameOf(id: String): String = ExtRegistry.get(id)?.name ?: id.take(8)

    // ---------- page (called by EngineHost.page) ----------

    fun page(id: String): WebResourceResponse? {
        val sw = swOf(id) ?: return null
        val src = android.net.Uri.encode(sw.path, "/")
        val html = "<!doctype html><meta charset=\"utf-8\"><title>MGB extension worker</title>" +
            "<script>" + PRE + "</script>" +
            "<script" + (if (sw.module) " type=\"module\"" else "") + " src=\"" + src + "\"></script>" +
            "<script>" + POST + "</script>"
        return WebResourceResponse("text/html", "utf-8", 200, "OK", hashMapOf("Cache-Control" to "no-store"), ByteArrayInputStream(html.toByteArray()))
    }

    private fun denied(): WebResourceResponse =
        WebResourceResponse("text/plain", "utf-8", 404, "Not Found", emptyMap(), ByteArrayInputStream(ByteArray(0)))

    // ---------- activity ----------

    fun touch(w: WebView) {
        for (b in bgs.values) if (b.web === w) { b.lastActive = SystemClock.uptimeMillis(); return }
    }

    /** A reply from this worker is awaited: do not stop it. Returns true if w is a worker. */
    fun hold(w: WebView): Boolean {
        val b = bgs.values.firstOrNull { it.web === w } ?: return false
        b.busy++
        b.lastActive = SystemClock.uptimeMillis()
        return true
    }

    fun release(w: WebView) {
        val b = bgs.values.firstOrNull { it.web === w } ?: return
        if (b.busy > 0) b.busy--
        b.lastActive = SystemClock.uptimeMillis()
    }

    private val tick = object : Runnable {
        override fun run() {
            val now = SystemClock.uptimeMillis()
            for (b in bgs.values.toList()) {
                val info = ExtRegistry.get(b.id)
                if (info == null || !info.enabled) { stop(b.id, "turned off"); continue }
                if (b.ready && b.busy == 0 && now - b.lastActive > IDLE_MS) stop(b.id, "idle")
            }
            if (bgs.isEmpty()) ticking = false else main.postDelayed(this, TICK_MS)
        }
    }

    // ---------- start / stop ----------

    /** Start the worker if needed; cb(true) when its listeners had time to register, cb(false) if it cannot run. */
    @SuppressLint("SetJavaScriptEnabled")
    fun ensure(id: String, cb: (Boolean) -> Unit) {
        ui {
            val a = app
            if (a == null || swOf(id) == null || id in parked) { cb(false); return@ui }
            val cur = bgs[id]
            if (cur != null) {
                cur.lastActive = SystemClock.uptimeMillis()
                if (cur.ready) cb(true) else cur.waiters.add(cb)
                return@ui
            }
            while (bgs.size >= MAX_RUNNING) {
                val old = bgs.values.minByOrNull { it.lastActive } ?: break
                stop(old.id, "too many background workers")
            }
            val w = try { WebView(a) } catch (e: Exception) {
                Diag.w("engine", "ext worker: WebView failed", e.message)
                cb(false)
                return@ui
            }
            val bg = Bg(id, w)
            bg.waiters.add(cb)
            w.settings.apply {
                javaScriptEnabled = true
                domStorageEnabled = true
                allowFileAccess = false
                allowContentAccess = false
                mediaPlaybackRequiresUserGesture = false
            }
            val own = ContentInjector.EXT_BASE + id + "/"
            w.webChromeClient = object : WebChromeClient() {
                override fun onConsoleMessage(m: ConsoleMessage): Boolean {
                    val line = "${m.message()}  (${m.sourceId()?.substringAfterLast('/')}:${m.lineNumber()})"
                    val lv = m.messageLevel()
                    if (lv == ConsoleMessage.MessageLevel.ERROR || lv == ConsoleMessage.MessageLevel.WARNING) log(id, line, lv == ConsoleMessage.MessageLevel.ERROR)
                    Log.d(TAG, line.take(300))
                    return true
                }
            }
            w.webViewClient = object : WebViewClient() {
                override fun shouldInterceptRequest(view: WebView, request: WebResourceRequest): WebResourceResponse? {
                    val u = request.url.toString()
                    touch(view)
                    if (u.startsWith(ContentInjector.EXT_BASE)) {
                        if (!u.startsWith(own)) return denied() // never another extension's (or the built-in) files
                        return EngineHost.ext(request.url) ?: denied()
                    }
                    EngineHost.ext(request.url)?.let { return it }
                    // network: CORS-free proxy only for the host permissions of this extension
                    if (!ContentInjector.urlAllowed(ExtApi.hostPats(id), u)) return null
                    return EngineHost.proxyFor(request, -1, id) // S7: header rules of this extension
                }

                override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean = true

                override fun onPageFinished(view: WebView, url: String?) {
                    val b = bgs[id]
                    if (b == null || b.web !== view || b.loaded || url == null || !url.startsWith(own + PAGE)) return
                    b.loaded = true
                    b.timeout?.let { main.removeCallbacks(it) }
                    b.timeout = null
                    main.postDelayed({
                        if (bgs[id] === b) {
                            b.ready = true
                            b.lastActive = SystemClock.uptimeMillis()
                            val ws = ArrayList(b.waiters)
                            b.waiters.clear()
                            for (f in ws) { try { f(true) } catch (e: Exception) { Log.e(TAG, "waiter", e) } }
                        }
                    }, SETTLE_MS)
                }

                override fun onReceivedError(view: WebView, request: WebResourceRequest, error: WebResourceError) {
                    if (request.isForMainFrame) {
                        log(id, "load error " + error.description)
                        main.post { if (bgs[id]?.web === view) stop(id, "load error") }
                    }
                }

                override fun onRenderProcessGone(view: WebView, detail: RenderProcessGoneDetail): Boolean {
                    main.post { if (bgs[id]?.web === view) crashed(id) }
                    return true
                }
            }
            ContentInjector.attachExt(a, w) // window.chrome for this extension (chosen by the page path)
            bgs[id] = bg
            ExtApi.bgStarted(id)
            val t = Runnable {
                log(id, "did not load in ${LOAD_TIMEOUT_MS / 1000} s")
                stop(id, "load timeout")
            }
            bg.timeout = t
            main.postDelayed(t, LOAD_TIMEOUT_MS)
            try { w.onResume(); w.resumeTimers() } catch (e: Exception) { Log.e(TAG, "resume", e) }
            w.loadUrl(own + PAGE)
            if (!ticking) { ticking = true; main.postDelayed(tick, TICK_MS) }
            EngineHost.addLog("ext worker started: " + nameOf(id))
        }
    }

    private fun crashed(id: String) {
        val now = SystemClock.uptimeMillis()
        val l = crashes.getOrPut(id) { ArrayList() }
        l.add(now)
        l.removeAll { now - it > CRASH_WINDOW_MS }
        if (l.size >= CRASH_LIMIT) {
            parked.add(id)
            log(id, "worker parked after repeated crashes")
        }
        Diag.w("engine", "ext worker render process gone", nameOf(id))
        stop(id, "render process gone")
    }

    fun stop(id: String, why: String) {
        ui {
            val b = bgs.remove(id)
            if (b != null) {
                b.timeout?.let { main.removeCallbacks(it) }
                b.timeout = null
                val ws = ArrayList(b.waiters)
                b.waiters.clear()
                ChromeBridge.unbind(b.web)
                try { b.web.stopLoading() } catch (_: Exception) { }
                b.web.webChromeClient = null
                main.post { try { b.web.destroy() } catch (e: Exception) { Log.e(TAG, "destroy", e) } }
                EngineHost.addLog("ext worker stopped: " + nameOf(id) + " (" + why + ")")
                for (f in ws) { try { f(false) } catch (e: Exception) { Log.e(TAG, "waiter", e) } }
            }
        }
    }

    fun stopAll(why: String) {
        for (id in bgs.keys.toList()) stop(id, why)
    }

    /** diag = also goes to the Diagnose report (tag "ext", S8). Warnings of the worker stay in the engine log only. */
    private fun log(id: String, line: String, diag: Boolean = true) {
        if (diag) Diag.w("ext", if (line.startsWith("worker parked")) "worker parked" else if (line.startsWith("load error") || line.startsWith("did not load")) "worker did not start" else "worker error", nameOf(id) + ": " + line.take(160))
        val l = logs.getOrPut(id) { ArrayList() }
        l.add(line.take(300))
        if (l.size > 30) l.removeAt(0)
        EngineHost.addLog("ext " + nameOf(id) + ": " + line.take(200))
    }

    fun status(): String {
        val sb = StringBuilder("\nExtension workers: ").append(bgs.size).append(" running")
        val now = SystemClock.uptimeMillis()
        for (b in bgs.values) {
            sb.append("\n  ").append(nameOf(b.id)).append(": ").append(if (b.ready) "ready" else "loading")
                .append(", idle ").append((now - b.lastActive) / 1000).append("s")
        }
        if (parked.isNotEmpty()) sb.append("\n  parked (crashes): ").append(parked.joinToString { nameOf(it) })
        return sb.toString()
    }
}
